import { readFile, writeFile } from "node:fs/promises"

const check = process.argv.includes("--check")
const root = new URL("../", import.meta.url)
const source = "crates/tauri-plugin-hasgard/src/protocol.rs"
const rust = await readFile(new URL(source, root), "utf8")
const cases = await readFile(new URL("protocol/responses.json", root), "utf8")
const limit = rust.match(/^pub\(crate\) const MAX_REQUEST_BYTES: usize = ([\d_]+);$/m)
if (!limit) throw new Error(`${source} must declare MAX_REQUEST_BYTES as an integer literal`)
const maxRequestBytes = Number(limit[1].replaceAll("_", ""))
if (!Number.isSafeInteger(maxRequestBytes) || maxRequestBytes <= 0) throw new Error("Invalid maxRequestBytes")
const banner = `// Generated by scripts/sync-protocol.mjs from ${source}. Do not edit.\n`
const outputs = new Map([
  [
    "crates/tauri-hasgard-cli/src/protocol.rs",
    banner +
      '#![allow(dead_code, reason = "Shared protocol includes server constructors and error constants")]\n' +
      rust
  ],
  ["packages/playwright/src/protocol-limits.ts", banner + `export const MAX_REQUEST_BYTES = ${maxRequestBytes}\n`],
  ["crates/tauri-plugin-hasgard/src/protocol-responses.json", cases],
  ["crates/tauri-hasgard-cli/src/protocol-responses.json", cases]
])

for (const [path, expected] of outputs) {
  const url = new URL(path, root)
  if (check) {
    const actual = await readFile(url, "utf8")
    if (actual !== expected) throw new Error(`${path} is stale; run bun scripts/sync-protocol.mjs`)
  } else {
    await writeFile(url, expected)
  }
}
